static bool p1FacesLeft() {
    const uint32_t game = 0x458B00;                // exists[] at +4, object*[] at +0x194
    if (!M[game + 4]) return false;
    uint32_t obj = RD32(game + 0x194);
    return obj && M[obj + 0x80] != 0;
}

static bool specialShortcut(const PadState& p, bool up, bool down, bool left, bool right) {
    bool atk = p.role(R_ATTACK), jmp = p.role(R_JUMP), def = p.role(R_DEFEND);
    bool action = atk || jmp || def;
    bool newAction = action && !g_prevAction;
    g_prevAction = action;
    if (g_macroPos < g_macro.size()) {             // playing
        while (g_macroPos < g_macro.size() && g_macro[g_macroPos].frame <= g_gameFrame) {
            key(g_macro[g_macroPos].vk, g_macro[g_macroPos].down);
            ++g_macroPos;
        }
        return true;
    }
    if (g_macroLock) {                              // wait for release
        if (p.role(R_SPECIAL) || action || up || down || left || right) return true;
        g_macroLock = false;
        return false;
    }
    bool spec = p.role(R_SPECIAL);
    bool newSpec = spec && !g_prevSpec;
    g_prevSpec = spec;
    if (!g_inBattle) { g_specAt = 0; return false; }    // menus: the button does nothing
    // especial alone = D > A. Its partner button may come a moment later
    // (pressing two buttons "together"), so a lone press waits kSpecWait game
    // frames for ataque / pulo / defesa before firing D dir A.
    const uint32_t kSpecWait = 3;
    bool fire = false;
    int second = kAtk;                                    // A, J, or 0 for D J A
    if (spec && newAction) {
        fire = true;
        second = def ? 0 : atk ? kAtk : kJmp;
    } else if (newSpec && !action) {
        g_specAt = g_gameFrame;
        return true;
    } else if (g_specAt && (!spec || g_gameFrame - g_specAt >= kSpecWait)) {
        fire = true;
    } else if (g_specAt) {
        return true;                                      // waiting for a partner
    }
    if (!fire) return false;
    g_specAt = 0;
    std::vector<int> seq;
    if (!second) seq = {kDef, kJmp, kAtk};                            // D J A
    else {
        int dir = up ? kUp : down ? kDown : left ? kLeft : right ? kRight
                : (p1FacesLeft() ? kLeft : kRight);                 // forward
        seq = {kDef, dir, second};
    }
    for (int vk : {kUp, kDown, kLeft, kRight, kAtk, kJmp, kDef}) key(vk, false);
    g_macro.clear();
    g_macroPos = 0;
    uint32_t f = g_gameFrame + 1;
    for (int vk : seq) { g_macro.push_back({f, vk, true}); g_macro.push_back({f + 2, vk, false}); f += 3; }
    g_macroLock = true;
    return true;
}

static void pollPad() {
    PadState p;
    readPad(p);
    const int dz = 12000;
    bool up = p.up || p.ly < -dz, down = p.down || p.ly > dz;
    bool left = p.left || p.lx < -dz, right = p.right || p.lx > dz;
    titleMenu(p, up, down, left, right);
    key(0x70, p.role(R_PAUSE));   // F1
    key(0x73, p.role(R_BACK));    // F4
    key(0x74, p.role(R_SPEED));   // F5
    static bool hudHeld = false;
    if (p.role(R_HUD) && !hudHeld) toggleHud();
    hudHeld = p.role(R_HUD);
    if (specialShortcut(p, up, down, left, right)) return;
    key(kUp, up);
    key(kDown, down);
    key(kLeft, left);
    key(kRight, right);
    key(kAtk, p.role(R_ATTACK));
    key(kJmp, p.role(R_JUMP));
    key(kDef, p.role(R_DEFEND));
}

void pumpEvents() {
    SDL_Event e;
    while (SDL_PollEvent(&e)) {
        switch (e.type) {
        case SDL_QUIT: quit(); break;
        case SDL_JOYDEVICEADDED:
            openPad(e.jdevice.which);
            break;
        case SDL_JOYDEVICEREMOVED:
            if ((g_joy && SDL_JoystickInstanceID(g_joy) == e.jdevice.which) ||
                (g_pad && SDL_JoystickInstanceID(SDL_GameControllerGetJoystick(g_pad)) == e.jdevice.which)) {
                closePad();
                for (int i = 0; i < SDL_NumJoysticks(); ++i) { openPad(i); if (g_pad || g_joy) break; }
            }
            break;
#ifndef __vita__
        case SDL_KEYDOWN: case SDL_KEYUP: {
            // desktop: keyboard arrows/ZXC like the original's player 1
            SDL_Keycode k = e.key.keysym.sym;
            bool d = e.type == SDL_KEYDOWN;
            if (k == SDLK_UP) key(kUp, d);
            else if (k == SDLK_DOWN) key(kDown, d);
            else if (k == SDLK_LEFT) key(kLeft, d);
            else if (k == SDLK_RIGHT) key(kRight, d);
            else if (k == SDLK_z) key(kAtk, d);
            else if (k == SDLK_x) key(kJmp, d);
            else if (k == SDLK_c) key(kDef, d);
            else if (k >= SDLK_F1 && k <= SDLK_F12) key(0x70 + (k - SDLK_F1), d);
            else if (k == SDLK_RETURN) key(0x0D, d);
            else if (k == SDLK_h && d && !e.key.repeat) toggleHud();
            else if (k == SDLK_SPACE && d && atTitleMenu()) {       // desktop: click the title item
                mouseMove(kTitleX, kTitleY[g_titleItem]); mouseButton(true); g_clickUpAt = SDL_GetTicks() + 100;
            }
            break;
        }
#endif
        }
    }
    pollPad();
}

