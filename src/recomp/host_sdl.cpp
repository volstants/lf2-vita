// The log starts with the version and the date, so a stale file is obvious.
void log(const char* tag, const char* msg) {
    if (!g_log) {
        mkdirs(kLogPath);
        g_log = fopen(kLogPath, "w");
        if (g_log) {
            time_t t = time(nullptr);
            char when[32] = "?";
            if (struct tm* lt = localtime(&t)) strftime(when, sizeof when, "%Y-%m-%d %H:%M:%S", lt);
            fprintf(g_log, "[start] LF2 Vita v%s, %s\n", LF2_VITA_VERSION, when);
        }
    }
    if (g_log) { fprintf(g_log, "[%s] %s\n", tag, msg); fflush(g_log); }
}

