struct Cached { const uint8_t* src = nullptr; uint32_t bytes = 0; Mix_Chunk* chunk = nullptr; };
static std::map<int, Cached> g_chunks;
static Mix_Music* g_music = nullptr;
static int g_musicVol = MIX_MAX_VOLUME;

static float dbGain(int hundredths) {
    if (hundredths <= -10000) return 0.f;
    return std::pow(10.f, (float)hundredths / 2000.f);
}

// Sound effects arrive as the game's own PCM (8/16-bit mono at 10-44 kHz) and
// are converted once to the mixer's format. SDL's own converter (a windowed
// sinc resampler) took ~2 ms per sound on a desktop PC, i.e. tens of ms on the
// Vita, on the first play of each sound in the middle of a fight: a visible
// hitch. Linear interpolation is ~9x cheaper (all 107 sounds: 207 -> 23 ms on
// the PC; the difference to SDL's output is ~24 dB below the signal).
// Converted sounds are shared by PCM address, so the game's duplicated
// buffers (same samples, other id) are converted only once.
// Converted sounds, shared by PCM address (the game's duplicated buffers hold
// the same samples under another id). The v2.05 log showed ~20 ms per sound on
// the Vita and the fight hitches lined up with the first plays, so the game's
// sounds are now converted by a background thread as soon as the game fills
// them (dsb Unlock -> soundPrepare, during the "game start" load); a play that
// still finds its sound unconverted converts it on the spot.
typedef std::pair<const uint8_t*, uint32_t> SndKey;
static std::map<SndKey, Mix_Chunk*> g_converted;
static SDL_mutex* g_sndLock = nullptr;
static SDL_sem* g_sndSem = nullptr;
struct SndJob { const uint8_t* pcm; uint32_t bytes; int ch, rate, bits; };
static std::vector<SndJob> g_sndJobs;
static Uint64 g_sndTicks = 0, g_sndBgTicks = 0;          // at first play / in the background
static uint32_t g_sndConversions = 0, g_sndBgConversions = 0;

static Mix_Chunk* convertSound(const uint8_t* pcm, uint32_t bytes, int channels, int rate, int bits) {
    int outRate, outCh;
    Uint16 outFmt;
    Mix_QuerySpec(&outRate, &outFmt, &outCh);
    int inCh = channels == 2 ? 2 : 1, bps = bits == 8 ? 1 : 2;
    uint32_t n = bytes / (uint32_t)(inCh * bps);
    if (outFmt == AUDIO_S16SYS && (outCh == 1 || outCh == 2) && rate > 0 && n > 0) {
        auto sample = [&](uint32_t k, int c) -> int {
            const uint8_t* q = pcm + ((size_t)k * inCh + (inCh == 2 ? c : 0)) * bps;
            return bps == 1 ? ((int)q[0] - 128) << 8 : (int)(int16_t)(q[0] | q[1] << 8);
        };
        uint64_t outN = (uint64_t)n * (uint64_t)outRate / (uint64_t)rate;
        if (!outN) outN = 1;
        uint64_t step = ((uint64_t)rate << 32) / (uint64_t)outRate;   // 32.32 fixed point
        int16_t* out = (int16_t*)SDL_malloc((size_t)outN * outCh * 2);
        if (!out) return nullptr;
        uint64_t pos = 0;
        int16_t* o = out;
        for (uint64_t i = 0; i < outN; ++i, pos += step) {
            uint32_t k = (uint32_t)(pos >> 32);
            if (k >= n) k = n - 1;
            uint32_t k1 = k + 1 < n ? k + 1 : k;
            int f = (int)((pos >> 16) & 0xFFFF);
            if (inCh == 1) {                 // mono source: one value for every output channel
                int a = sample(k, 0), v = a + (((sample(k1, 0) - a) * f) >> 16);
                for (int c = 0; c < outCh; ++c) *o++ = (int16_t)v;
            } else {
                for (int c = 0; c < outCh; ++c) {
                    int a = sample(k, c), v = a + (((sample(k1, c) - a) * f) >> 16);
                    *o++ = (int16_t)v;
                }
            }
        }
        return Mix_QuickLoad_RAW((Uint8*)out, (Uint32)(outN * outCh * 2));
    }
    SDL_AudioCVT cvt;                        // any other mixer format: SDL's converter
    SDL_BuildAudioCVT(&cvt, bits == 8 ? AUDIO_U8 : AUDIO_S16LSB, (Uint8)channels, rate,
                      outFmt, (Uint8)outCh, outRate);
    cvt.len = (int)bytes;
    cvt.buf = (Uint8*)SDL_malloc((size_t)bytes * (cvt.len_mult > 0 ? cvt.len_mult : 1));
    memcpy(cvt.buf, pcm, bytes);
    if (cvt.needed) SDL_ConvertAudio(&cvt);
    return Mix_QuickLoad_RAW(cvt.buf, (Uint32)(cvt.needed ? cvt.len_cvt : cvt.len));
}
static void freeChunk(Mix_Chunk* c) {         // Mix_QuickLoad_RAW does not own its buffer
    if (!c) return;
    Uint8* buf = c->abuf;
    Mix_FreeChunk(c);
    SDL_free(buf);
}
// Stores `c` unless another thread converted the same sound meanwhile.
static Mix_Chunk* storeConverted(SndKey k, Mix_Chunk* c) {
    SDL_LockMutex(g_sndLock);
    Mix_Chunk*& slot = g_converted[k];
    if (!slot) slot = c; else { freeChunk(c); c = slot; }
    SDL_UnlockMutex(g_sndLock);
    return c;
}
static Mix_Chunk* findConverted(SndKey k) {
    SDL_LockMutex(g_sndLock);
    auto it = g_converted.find(k);
    Mix_Chunk* c = it == g_converted.end() ? nullptr : it->second;
    SDL_UnlockMutex(g_sndLock);
    return c;
}
static int soundWorker(void*) {
    SDL_SetThreadPriority(SDL_THREAD_PRIORITY_LOW);
    for (;;) {
        SDL_SemWait(g_sndSem);
        SDL_LockMutex(g_sndLock);
        if (g_sndJobs.empty()) { SDL_UnlockMutex(g_sndLock); continue; }
        SndJob j = g_sndJobs.front();
        g_sndJobs.erase(g_sndJobs.begin());
        bool done = g_converted.count({j.pcm, j.bytes}) != 0;
        SDL_UnlockMutex(g_sndLock);
        if (done) continue;
        Uint64 t0 = SDL_GetPerformanceCounter();
        Mix_Chunk* c = convertSound(j.pcm, j.bytes, j.ch, j.rate, j.bits);
        Uint64 t1 = SDL_GetPerformanceCounter();
        if (c) {
            storeConverted({j.pcm, j.bytes}, c);
            SDL_LockMutex(g_sndLock);
            g_sndBgTicks += t1 - t0;
            ++g_sndBgConversions;
            SDL_UnlockMutex(g_sndLock);
        }
    }
    return 0;
}
static void startSoundWorker() {
    g_sndLock = SDL_CreateMutex();
    g_sndSem = SDL_CreateSemaphore(0);
    if (!g_sndLock || !g_sndSem || !SDL_CreateThread(soundWorker, "lf2-sound-convert", nullptr))
        log("audio", "background sound conversion unavailable; converting at first play");
}

void soundPrepare(const uint8_t* pcm, uint32_t bytes, int channels, int rate, int bits) {
    if (!g_audio || !bytes || !g_sndSem) return;
    SDL_LockMutex(g_sndLock);
    g_sndJobs.push_back(SndJob{pcm, bytes, channels, rate, bits});
    SDL_UnlockMutex(g_sndLock);
    SDL_SemPost(g_sndSem);
}

void soundPlay(int id, const uint8_t* pcm, uint32_t bytes, int channels, int rate, int bits,
               int vol, int pan) {
    if (!g_audio || !bytes) return;
    Cached& c = g_chunks[id];
    if (!c.chunk || c.src != pcm || c.bytes != bytes) {
        SndKey k{pcm, bytes};
        Mix_Chunk* conv = findConverted(k);
        if (!conv) {                         // not ready yet: convert now (a possible hitch)
            Uint64 t0 = SDL_GetPerformanceCounter();
            conv = convertSound(pcm, bytes, channels, rate, bits);
            g_sndTicks += SDL_GetPerformanceCounter() - t0;
            ++g_sndConversions;
            if (conv) conv = storeConverted(k, conv);
        }
        c.chunk = conv;
        c.src = pcm; c.bytes = bytes;
    }
    if (!c.chunk) return;
    int ch = id % 256;
    Mix_HaltChannel(ch);
    Mix_Volume(ch, (int)(MIX_MAX_VOLUME * dbGain(vol) + 0.5f));
    float l = pan > 0 ? dbGain(-pan) : 1.f, r = pan < 0 ? dbGain(pan) : 1.f;
    Mix_SetPanning(ch, (Uint8)(255 * l), (Uint8)(255 * r));
    Mix_PlayChannel(ch, c.chunk, 0);
}
void soundStop(int id) { if (g_audio) Mix_HaltChannel(id % 256); }

void musicPlay(const std::string& windowsPath) {
    if (!g_audio) return;
    if (g_music) { Mix_HaltMusic(); Mix_FreeMusic(g_music); g_music = nullptr; }
    if (windowsPath.empty()) return;
    std::string p = windowsPath;
    size_t dot = p.find_last_of('.');
    if (dot != std::string::npos) p = p.substr(0, dot) + ".ogg";
    std::string path;
    if (!resolve(p, path) && !resolve(windowsPath, path)) return;
    g_music = Mix_LoadMUS(path.c_str());
    if (g_music) { Mix_VolumeMusic(g_musicVol); Mix_PlayMusic(g_music, -1); }
}
void musicStop() { if (g_audio && g_music) Mix_HaltMusic(); }
void musicVolume(int hundredths) {
    g_musicVol = (int)(MIX_MAX_VOLUME * dbGain(hundredths) + 0.5f);
    if (g_audio) Mix_VolumeMusic(g_musicVol);
}

