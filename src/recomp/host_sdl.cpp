// Player 1 keys come from data\control.txt (first line), read at startup.
static int kUp = 104, kDown = 98, kLeft = 100, kRight = 102, kAtk = 101, kJmp = 96, kDef = 107;
static bool g_held[256];
static int g_mx = 0, g_my = 0;
static bool g_mouseDown = false;

static void key(int vk, bool down) {
    if (vk <= 0 || vk > 255) return;
    if (g_held[vk] == down) return;
    g_held[vk] = down;
    win32::postMessage(down ? 0x100 : 0x101, (uint32_t)vk, down ? 1u : 0xC0000001u);
}
static void mouseMove(int x, int y) {
    g_mx = x < 0 ? 0 : x > 793 ? 793 : x;
    g_my = y < 0 ? 0 : y > 549 ? 549 : y;
    win32::postMessage(0x200, g_mouseDown ? 1u : 0u, ((uint32_t)g_my << 16) | (uint32_t)g_mx);
}
static void mouseButton(bool down) {
    if (g_mouseDown == down) return;
    g_mouseDown = down;
    win32::postMessage(down ? 0x201 : 0x202, down ? 1u : 0u, ((uint32_t)g_my << 16) | (uint32_t)g_mx);
}

