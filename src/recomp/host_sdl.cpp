static bool resolve(const std::string& rel, std::string& out) {
    std::string p = rel;
    for (char& c : p) if (c == '\\') c = '/';
    std::string direct = g_root + p;
    if (FILE* f = fopen(direct.c_str(), "rb")) { fclose(f); out = direct; return true; }
    // case-insensitive walk (desktop filesystems)
    std::string cur = g_root.substr(0, g_root.size() - 1);
    size_t start = 0;
    while (start <= p.size()) {
        size_t e = p.find('/', start);
        if (e == std::string::npos) e = p.size();
        std::string seg = p.substr(start, e - start);
        start = e + 1;
        if (seg.empty()) continue;
        DIR* d = opendir(cur.c_str());
        if (!d) return false;
        std::string found;
        while (dirent* de = readdir(d))
            if (strcasecmp(de->d_name, seg.c_str()) == 0) { found = de->d_name; break; }
        closedir(d);
        if (found.empty()) return false;
        cur += "/" + found;
    }
    out = cur;
    return true;
}

static std::string overlayPath(const std::string& rel);
static bool overlayHas(const std::string& rel);
static uint32_t g_ioFiles = 0, g_ioBytes = 0;
static Uint64 g_ioTicks = 0;

static bool readWhole(FILE* f, std::vector<uint8_t>& out) {
    fseek(f, 0, SEEK_END);
    long n = ftell(f);
    fseek(f, 0, SEEK_SET);
    out.resize(n > 0 ? (size_t)n : 0);
    size_t got = n > 0 ? fread(out.data(), 1, (size_t)n, f) : 0;
    fclose(f);
    return got == out.size();
}

// One open per file on the Vita: the save overlay is consulted only for the
// files known to be there (listed at startup + those written since), and the
// game folder is opened directly (FAT/exFAT are case-insensitive); the
// case-insensitive walk is only a fallback for desktop filesystems.
// Whole file in one go. On the Vita, newlib's fread moves the data through a
// small FILE buffer, i.e. thousands of sceIoRead calls per sprite sheet: the
// v2.05 log showed 13.2 s of I/O for the 28.3 MB read at "game start"
// (~2 MB/s). sceIoRead straight into the destination does it in one call.
static bool readPath(const std::string& path, std::vector<uint8_t>& out) {
#ifdef __vita__
    SceUID fd = sceIoOpen(path.c_str(), SCE_O_RDONLY, 0);
    if (fd < 0) return false;
    SceOff n = sceIoLseek(fd, 0, SCE_SEEK_END);
    sceIoLseek(fd, 0, SCE_SEEK_SET);
    if (n < 0) { sceIoClose(fd); return false; }
    out.resize((size_t)n);
    size_t got = 0;
    while (got < out.size()) {
        int r = sceIoRead(fd, out.data() + got, (SceSize)(out.size() - got));
        if (r <= 0) break;
        got += (size_t)r;
    }
    sceIoClose(fd);
    return got == out.size();
#else
    FILE* f = fopen(path.c_str(), "rb");
    return f && readWhole(f, out);
#endif
}

bool readFile(const std::string& rel, std::vector<uint8_t>& out) {
    Uint64 t0 = SDL_GetPerformanceCounter();
    bool ok = false;
    if (overlayHas(rel)) ok = readPath(overlayPath(rel), out);
    if (!ok) {
        std::string p = rel;
        for (char& c : p) if (c == '\\') c = '/';
        ok = readPath(g_root + p, out);
    }
    if (!ok) {
        std::string path;
        if (resolve(rel, path)) ok = readPath(path, out);
    }
    g_ioTicks += SDL_GetPerformanceCounter() - t0;
    if (ok) { ++g_ioFiles; g_ioBytes += (uint32_t)out.size(); }
    return ok;
}

// Files the game writes (control.txt, recordings) go to a writable overlay
// that readFile consults first: the game folder itself may be read-only
// (app0:) and must stay pristine.
#ifdef __vita__
static const char* kSaveDir = "ux0:data/lf2vita/";
#else
static const char* kSaveDir = "./lf2save/";
#endif
static std::string overlayKey(const std::string& rel) {
    std::string p = rel;
    for (char& c : p) { if (c == '\\') c = '/'; c = (char)tolower((unsigned char)c); }
    return p;
}
static std::string overlayPath(const std::string& rel) { return std::string(kSaveDir) + overlayKey(rel); }
static std::set<std::string> g_overlay;          // files present in the save overlay
static void scanOverlay(const std::string& dir, const std::string& prefix) {
    DIR* d = opendir(dir.c_str());
    if (!d) return;
    while (dirent* de = readdir(d)) {
        std::string n = de->d_name;
        if (n == "." || n == "..") continue;
        std::string full = dir + "/" + n;
        struct stat st;
        if (stat(full.c_str(), &st) == 0 && S_ISDIR(st.st_mode)) scanOverlay(full, prefix + n + "/");
        else g_overlay.insert(overlayKey(prefix + n));
    }
    closedir(d);
}
static bool overlayHas(const std::string& rel) { return g_overlay.count(overlayKey(rel)) != 0; }
static void mkdirs(const std::string& path) {   // every directory of `path`
    for (size_t i = 1; i < path.size(); ++i)
        if (path[i] == '/') {
            std::string d = path.substr(0, i);
#ifdef __vita__
            sceIoMkdir(d.c_str(), 0777);
#else
            mkdir(d.c_str(), 0777);
#endif
        }
}
void writeFile(const std::string& rel, const std::vector<uint8_t>& data) {
    std::string p = overlayPath(rel);
    mkdirs(p);
    if (FILE* f = fopen(p.c_str(), "wb")) {
        fwrite(data.data(), 1, data.size(), f);
        fclose(f);
        g_overlay.insert(overlayKey(rel));
    }
}

