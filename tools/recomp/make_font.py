"""Generate src/recomp/gdi_font.h: a 1-bit proportional bitmap font standing in
for the Windows "System" font that GDI TextOut uses in lf2.exe (cell height 16).
Source: DejaVu Sans Bold (free license), rendered without antialiasing."""
import pathlib, sys
from PIL import Image, ImageDraw, ImageFont
ROOT = pathlib.Path(__file__).resolve().parents[2]
FONT = "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"
SIZE = 12
H = 16
f = ImageFont.truetype(FONT, SIZE)
asc, desc = f.getmetrics()
top = (H - (asc + desc)) // 2 + 1
widths, rows = [], []
for c in range(256):
    ch = chr(c) if c >= 32 and c != 127 else " "
    try:
        ch.encode("latin1")
    except UnicodeEncodeError:
        ch = " "
    w = max(1, int(round(f.getlength(ch))))
    if c < 32: w = 0
    img = Image.new("1", (w + 2, H), 0)
    d = ImageDraw.Draw(img)
    d.fontmode = "1"
    d.text((0, top), ch, font=f, fill=1)
    widths.append(w)
    for y in range(H):
        bits = 0
        for x in range(min(w, 16)):
            if img.getpixel((x, y)): bits |= 1 << x
        rows.append(bits)
out = ["// generated by tools/recomp/make_font.py — do not edit",
       "#pragma once", "#include <cstdint>",
       "namespace gdifont {", "constexpr int H = %d;" % H,
       "static const uint8_t W[256] = {%s};" % ",".join(map(str, widths)),
       "static const uint16_t ROWS[256 * H] = {"]
for i in range(0, len(rows), 16):
    out.append("  " + ",".join("0x%04x" % r for r in rows[i:i + 16]) + ",")
out += ["};", "}"]
(ROOT / "src/recomp/gdi_font.h").write_text("\n".join(out) + "\n")
if len(sys.argv) > 1:
    s = "Player 1  Davis  Team 1  How many?  0 1 2 3"
    x = 0
    img = Image.new("L", (400, H), 0)
    for ch in s:
        c = ord(ch)
        for y in range(H):
            for b in range(widths[c]):
                if rows[c * H + y] >> b & 1: img.putpixel((x + b, y), 255)
        x += widths[c]
    img.resize((1600, 64)).save(sys.argv[1])
